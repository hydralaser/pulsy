"""Build words.js: the Italian word bank split into CEFR-style levels.

Order = frequency rank (tools/rank_lemmas.py over OpenSubtitles counts), glossed by hand in tools/gloss/*.txt
(one "italiano=english" per line, article on nouns, in rank order). Everyday basics from tools/curated.txt
(days, numbers, colours, food...) that subtitles under-rank are pulled up into A2 at the latest.
Band sizes mirror Linguno's WordBank levels so progress maps across roughly 1:1.
"""
import json, pathlib, re, unicodedata
here = pathlib.Path(__file__).parent
LEVELS = [('A1', 548), ('A2', 933), ('B1', 1561), ('B2', 1783), ('C1', 1073), ('C2', 611)]
ART = re.compile(r"^(?:(?:il|lo|la|i|gli|le|un|una|uno)\s+|(?:l|un)['’]\s*)", re.I)
def norm(s):
    s = ART.sub('', s.strip().lower()).replace('’', "'")
    return ''.join(c for c in unicodedata.normalize('NFD', s) if unicodedata.category(c) != 'Mn')
def pos(it, en):
    if ART.match(it) and not it.lower().startswith(('un po', "un'or")): return 'n'
    if en.startswith('to ') and re.search(r'(are|ere|ire|rre|arsi|ersi|irsi|rsi)$', it): return 'v'
    return 'x'
entries, seen = [], set()
for f in sorted((here / 'gloss').glob('*.txt')):
    for line in f.read_text(encoding='utf-8').splitlines():
        if '=' not in line: continue
        it, en = (x.strip() for x in line.split('=', 1))
        if not it or not en or en == '-' or norm(it) in seen: continue
        seen.add(norm(it)); entries.append((it, en, pos(it, en)))
curated = [l.split('|') for l in (here / 'curated.txt').read_text(encoding='utf-8').splitlines() if l]
a2_end = sum(n for _, n in LEVELS[:2])
rank = {norm(e[0]): i for i, e in enumerate(entries)}
pull = []
for it, en, p in curated:
    k = norm(it)
    if k in rank and rank[k] < a2_end: continue
    if k in rank:  # keep our gloss but move it up
        e = entries[rank[k]]; entries[rank[k]] = None; pull.append((e[0], e[1], p if p != 'x' else e[2]))
    else:
        pull.append((it, en, p))
entries = [e for e in entries if e]
cut = a2_end - len(pull)
entries = entries[:cut] + pull + entries[cut:]
out, i = {}, 0
for name, n in LEVELS:
    out[name] = ['|'.join(e) for e in entries[i:i + n]]; i += n
js = ('// Generated by tools/build_bank.py. Word order: subtitle frequency (FrequencyWords, CC BY-SA 4.0),\n'
      '// lemmatised with lemmatization-lists (ODbL). English glosses written for this app.\n'
      'export const WORD_LEVELS = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')
(here.parent / 'words.js').write_text(js, encoding='utf-8')
print({k: len(v) for k, v in out.items()}, 'pulled up', len(pull), 'total', len(entries))
